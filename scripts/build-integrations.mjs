import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const targets = [
  ['integrations/codex/c4/hooks/c4-hook.source.mjs', 'integrations/codex/c4/hooks/c4-hook.mjs', []],
  ['integrations/claude/c4/hooks/c4-hook.source.mjs', 'integrations/claude/c4/hooks/c4-hook.mjs', []],
  ['integrations/deepseek/c4/index.source.mjs', 'integrations/deepseek/c4/index.js', []],
  ['integrations/opencode/c4/index.source.mjs', 'integrations/opencode/c4/index.mjs', []],
];
for (const [entry, output, external] of targets) {
  await build({ entryPoints: [fileURLToPath(new URL(entry, root))], outfile: fileURLToPath(new URL(output, root)),
    bundle: true, platform: 'node', format: 'esm', target: 'node20', external,
    banner: { js: '// Generated by npm run integrations:build. Do not edit directly.' } });
  console.log(output);
}
await build({ entryPoints: [fileURLToPath(new URL('pi/c4.ts', root))], bundle: true,
  platform: 'node', format: 'esm', target: 'node20', write: false });
